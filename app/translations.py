def t(key: str, lang: str = 'gu') -> str:
    """Return translation string for key in specified language with fallback."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS['gu'])
    if key in lang_dict:
        return lang_dict[key]
    return TRANSLATIONS['gu'].get(key, key)
